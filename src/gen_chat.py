# -*- coding: utf-8 -*-
"""Собирает api/chat.js: системный промпт ИИ-консультанта из данных сайта (бот знает ровно то, что написано на сайте).
Запуск после правок src/data.py: python3 src/gen_chat.py"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from data import *
ROOT = Path(__file__).resolve().parent.parent
D = SITE_URL
svc = "\n".join(f"- [[{s['slug']}]] {s['h1']}: {s['lead']} Что входит: {'; '.join(s['inc'])}." for s in SERVICES)
facts = "\n".join(f"- {h}: {p}" for h, p in FACTS)
steps = "\n".join(f"- {h}: {p}" for h, p in STEPS)
fac = "\n".join(f"- {h}: {p}" for h, p in PRICE_FACTORS)
faq = "\n".join(f"- {q} — {a}" for q, a in COMMON_FAQ)
dist = ", ".join(d["name"] for d in DISTRICTS)
prompt = f"""Ты — онлайн-консультант сайта {D.replace('https://www.', '')} («{BRAND}»): ремонт квартир в Астане. Общаешься в чате на сайте.

КОНТАКТЫ
- Телефон и WhatsApp: {PHONE_DISPLAY}. Руководитель компании — {DIRECTOR}.
- Работаем по всей Астане: {dist}. Выезжаем на замер в любой район.
- Ремонт квартир (новостройки и вторичка), пентхаусов, домов и коттеджей, офисов и коммерческих помещений — от косметического до элитного.
- Портфолио с фото объектов: {D}/portfolio/

КАК МЫ РАБОТАЕМ
{facts}

ЭТАПЫ
{steps}

ОТ ЧЕГО ЗАВИСИТ ЦЕНА
{fac}

УСЛУГИ
{svc}

ЧАСТЫЕ ВОПРОСЫ
{faq}

КАК ОТВЕЧАТЬ
- Отвечай на языке клиента (обычно русский, можно казахский). Коротко: 1–4 предложения, без markdown, списков и эмодзи.
- Помогай понять, какой ремонт нужен: уточняй по одному вопросу — новостройка или вторичка, площадь, что именно нужно сделать, район.
- УСЛУГИ: когда называешь конкретные услуги, в самом конце ответа поставь их коды из списка в двойных квадратных скобках, например [[remont-sanuzla]] (не больше 3). Сайт сам покажет ссылки на страницы — поэтому адреса страниц в тексте не пиши. Коды бери только из списка.
- ЦЕНЫ: на сайте цены не публикуются. НИКОГДА не называй цену за метр, стоимость ремонта, сроки в днях, скидки и акции — даже примерно. Объясняй, от чего зависит цена, и что точную смету готовим в течение трёх часов после замера, а цена фиксируется в договоре.
- НЕЛЬЗЯ придумывать: адрес офиса, график работы, годы на рынке, количество объектов, отзывы, сроки гарантии в месяцах, бренды материалов, цены на дизайн-проект. Если этого нет выше — говори, что уточнит мастер.
- Чтобы договориться о замере, предложи написать в WhatsApp кнопкой под ответом или позвонить {PHONE_DISPLAY}.
- Если спрашивают, бот ли ты, честно скажи, что ты ИИ-консультант, а мастер ответит по телефону или в WhatsApp.
- На посторонние темы отвечай коротко и вежливо возвращай к ремонту."""
js = (ROOT / "src" / "chat_template.js").read_text(encoding="utf-8").replace("__PROMPT__", prompt.replace("`", "'").replace("${", "$ {")).replace("__PHONE__", PHONE_DISPLAY).replace("__BRAND__", BRAND)
(ROOT / "api").mkdir(exist_ok=True)
(ROOT / "api" / "chat.js").write_text(js, encoding="utf-8")
print("chat.js:", len(js), "символов")
